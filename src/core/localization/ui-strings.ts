const tables: Record<Lang, Record<StringKey, string>> = { en, ar };

const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
export function formatNumber(n: number, lang: Lang): string {
  const s = String(n);
  return lang === 'ar' ? s.replace(/\d/g, (d) => AR_DIGITS[Number(d)]) : s;
}

export function translate(lang: Lang, key: StringKey, vars?: Record<string, string | number>): string {
  let s = tables[lang][key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, typeof v === 'number' ? formatNumber(v, lang) : v);
  }
  return s;
}
