export const v3 = (lang: Lang): Strings => (lang === 'ar' ? ar : en);

export function fmt(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

const numFmt: Partial<Record<Lang, Intl.NumberFormat>> = {};
export function num(n: number, lang: Lang): string {
  numFmt[lang] ??= new Intl.NumberFormat(lang === 'ar' ? 'ar-SA' : 'en-US');
  return numFmt[lang]!.format(n);
}

/** fmt with numbers localized (Arabic-Indic digits in Arabic). */
export function nfmt(s: string, vars: Record<string, string | number>, lang: Lang): string {
  return fmt(s, Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, typeof v === 'number' ? num(v, lang) : v])));
}

export function errText(code: string, lang: Lang): string {
  const t = v3(lang) as Record<string, string>;
  return t[`err_${code}`] ?? t.err_offline;
}
