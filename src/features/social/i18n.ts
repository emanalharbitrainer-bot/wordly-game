export const sx = (l: Lang): Strings => (l === 'en' ? en : ar);
export const sfmt = (s: string, v: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(v[k] ?? ''));
const NF = { ar: new Intl.NumberFormat('ar-SA'), en: new Intl.NumberFormat('en-US') };
export const num = (n: number, l: Lang) => NF[l === 'ar' ? 'ar' : 'en'].format(n);
export const errText = (l: Lang, e: unknown) => {
  const code = e && typeof e === 'object' && 'code' in e ? String((e as { code: string }).code) : 'server';
  return sx(l).err[code] ?? sx(l).err.server;
};

/** "3 أيام" / "يومان" / "11 يوم" — Arabic counted-noun agreement; "1 day" / "3 days" in English. */
export function daysText(n: number, l: Lang): string {
  if (l === 'en') return `${num(n, 'en')} ${n === 1 ? 'day' : 'days'}`;
  if (n === 1) return 'يوم واحد';
  if (n === 2) return 'يومان';
  if (n >= 3 && n <= 10) return `${num(n, l)} أيام`;
  return `${num(n, l)} يوم`;
}
